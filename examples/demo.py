def build(output):
    root=Path(output).resolve(); root.mkdir(parents=True,exist_ok=False)
    (root/"figures").mkdir()
    rows,splits=generate_data(root); eda(root,rows,splits)
    environment=capture_environment(Path(__file__).resolve().parents[1])
    paths={k:design(root,rows,splits,environment,k) for k in ("majority","logistic")}
    entries=[run(root,paths["majority"],"majority","majority"),run(root,paths["logistic"],"logistic")]
    for fault in ("optimizer","metric"):
        entries.append(run(root,paths["logistic"],f"wrong-{fault}",fault=fault))
    (root/"brief.md").write_text('''# Research brief

Product objective: demonstrate a dependable CPU research workflow with durable evidence. Scientific question: does a learned one-feature sensor classifier improve on majority prediction? Data: synthetic, complete binary labels, two readings per independent sensor group. Budget: 120 full-batch updates, one training/data seed, no GPU or service. Success: catch invalid runs and preserve comparable results; a validation gain >=0.10 is promising but not evidence of robustness. Non-goal: a real-world sensor benchmark or causal model of sensor behavior.
''')
    save_json(root/"hypotheses.json", [{"id":"H1","statement":"A one-feature logistic classifier improves validation accuracy over majority by >=0.10", "rivals":["Majority balance explains apparent gains","Measurement/label noise determines errors"],"falsification":"Gain below 0.10 on independent replication fails the useful-effect criterion", "status":"inconclusive", "confounders":["single data seed","synthetic distribution"],"next_test":"paired independent seed replication"}])
    (root/"roadmap.md").write_text('''# Roadmap

Completed: train-only EDA, frozen group splits, majority baseline, logistic comparison, runtime and artifact verification, exploratory error analysis. Next milestone: independently replicate useful-effect criterion. Cost: CPU minutes. Decision changed: whether to commit to real sensor data. Defer complex models until that gate; final test remains sealed. Stop if benefit disappears across groups/seeds.
''')
    report(root,rows,entries)
    project={"schema_version":1,"id":"sensor-study","title":"Synthetic sensor classification","objective":"Demonstrate trustworthy local research and continuity", "question":"Does a learned sensor-score classifier improve over a majority baseline?", "status":"paused", "pause_reason":"Demo milestone complete; multi-seed robustness study needs a new design.",
             "hypotheses":[{"id":"H1","statement":"Learned score improves accuracy by at least 0.10","status":"inconclusive"}],"runs":entries,
             "findings":[{"id":"F1","kind":"observation","claim":"Fixed-split classifier and baseline results are recorded; interpretation is limited to one seed.","run_ids":["logistic","majority"],"evidence":["comparison.json","summary.md"]},
                         {"id":"F2","kind":"negative-result","claim":"Wrong optimizer and reported metric invalidate those executions, not H1.","run_ids":["wrong-optimizer","wrong-metric"],"evidence":["runs/wrong-optimizer/verification.json","runs/wrong-metric/verification.json"]}],
             "next_experiments":["Parameterize the fixed generator seed and predeclare paired independent data-seed replication", "Controlled noise versus nonlinear-boundary experiment"],
             "documents":["brief.md","eda.md","hypotheses.json","roadmap.md","failure-analysis.md","ablation-review.md","summary.md","retro.md","blog.md","decisions.md","handoff.md"]}
    save_json(root/"project.json",project)
    (root/"resume.md").write_text(resume_report(root))
    print(json.dumps({"project":str(root),"eligible_cohorts":best_runs(root)},indent=2))
    return root


